#!/usr/bin/env python3
"""Writes the AmiSSL glue of the AmigaOS 4 build. Public domain.

    python3 -I tools/gen_amissl_glue.py OUTDIR

AmiSSL 5 (OpenSSL 3, AMISSL_V3xx) and AmiSSL 6 (OpenSSL 4, AMISSL_V4xx) have
different interface tables, so the SDK's stub library (fixed AmiSSL 5
offsets) cannot be used if both are to work. Instead every function in
tools/amissl_functions.txt gets a stub here that calls through amissl_fn[],
which src/os4/amissl.c fills from the opened interface using the offsets of
that AmiSSL version:

    OUTDIR/amissl_glue.c    the stubs (prototypes from the AmiSSL 5 SDK's
                            amissl.xml; compiled with the AmiSSL 5 headers)
    OUTDIR/amissl_off_v3.c  offsetof() each function in the AmiSSL 5
                            interface (compiled with the AmiSSL 5 headers)
    OUTDIR/amissl_off_v4.c  the same for AmiSSL 6 (compiled with the AmiSSL 6
                            headers first), and AMISSL_V4xx

tools/check_amissl_api.py checks that the prototypes are the same in both.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
XML = os.path.join(ROOT, "build", "deps", "amissl-sdk", "AmiSSL", "Developer", "xml", "amissl.xml")
LIST = os.path.join(ROOT, "tools", "amissl_functions.txt")

HEAD = """/* Generated by tools/gen_amissl_glue.py - do not edit. Public domain. */
"""
INCLUDES = """#include <stddef.h>
#include <proto/amissl.h>
"""


def functions():
    with open(LIST) as f:
        return [line.strip() for line in f if line.strip() and not line.startswith("#")]


def prototypes():
    with open(XML, encoding="latin-1") as f:
        xml = f.read()
    protos = {}
    for m in re.finditer(r'<method\s+name="([^"]+)"\s+result="([^"]*)"[^>]*?(/>|>(.*?)</method>)', xml, re.S):
        args = re.findall(r'<arg\s+name="[^"]*"\s+type="([^"]*)"', m.group(4) or "")
        protos[m.group(1)] = (m.group(2), args)
    return protos


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    names = functions()
    protos = prototypes()
    missing = [n for n in names if n not in protos]
    if missing:
        sys.exit("not in the AmiSSL SDK: " + " ".join(missing))
    n = len(names)

    glue = [HEAD, INCLUDES, "#include <openssl/bio.h>", "#include <openssl/bn.h>",
            "#include <openssl/crypto.h>", "#include <openssl/ec.h>", "#include <openssl/err.h>",
            "#include <openssl/evp.h>", "#include <openssl/pem.h>", "#include <openssl/rand.h>",
            "#include <openssl/params.h>", "",
            "/* filled by amissl_open() from the opened AmiSSL interface */",
            "void *amissl_fn[%d];" % n, "const int amissl_nfn = %d;" % n, ""]
    for i, name in enumerate(names):
        res, types = protos[name]
        for t in [res] + types:
            if "(" in t or "..." in t:
                sys.exit("%s: function pointer or varargs, write its stub by hand" % name)
        params = ", ".join("%s a%d" % (t, k) for k, t in enumerate(types)) or "void"
        fptr = "%s (*)(%s)" % (res, ", ".join(["struct AmiSSLIFace *"] + types))
        call = "((%s)amissl_fn[%d])(%s)" % (fptr, i, ", ".join(["IAmiSSL"] + ["a%d" % k for k in range(len(types))]))
        ret = "" if res.strip() == "void" else "return "
        glue += ["%s %s(%s)" % (res, name, params), "{", "\t%s%s;" % (ret, call), "}", ""]
    with open(os.path.join(out, "amissl_glue.c"), "w") as f:
        f.write("\n".join(glue))

    for ver, extra in (("v3", ""), ("v4", "\nconst int amissl_v4xx = AMISSL_V4xx;\n")):
        lines = [HEAD, INCLUDES, "#include <libraries/amisslmaster.h>", "",
                 "const unsigned int amissl_off_%s[%d] = {" % (ver, n)]
        lines += ["\toffsetof(struct AmiSSLIFace, %s)," % name for name in names]
        lines += ["};", extra]
        with open(os.path.join(out, "amissl_off_%s.c" % ver), "w") as f:
            f.write("\n".join(lines))
    print("AmiSSL glue: %d functions -> %s" % (n, out))


if __name__ == "__main__":
    main()
